/** 默认专员 */
export const DEFAULT_AGENT_ID: CsAgentId = 'portal';

export function getAgent(id: string | null | undefined): CsAgent {
  return CS_AGENTS.find((a) => a.id === id) || CS_AGENTS[0];
}

/**
 * 根据用户这句话推荐更合适的专员。
 * 返回 null 表示当前专员就合适，不用切换。
 */
export function suggestAgent(message: string, currentId: CsAgentId): CsAgent | null {
  const text = message.toLowerCase();
  let best: { agent: CsAgent; score: number } | null = null;

  for (const agent of CS_AGENTS) {
    if (agent.id === currentId) continue;
    let score = 0;
    for (const kw of agent.keywords) {
      if (text.includes(kw.toLowerCase())) score += kw.length >= 3 ? 2 : 1;
    }
    // 总览专员的关键词太泛（"怎么用""有什么功能"），需要更高的门槛才推荐
    if (agent.id === 'portal') score -= 3;
    if (score > 0 && (!best || score > best.score)) best = { agent, score };
  }

  return best && best.score >= 2 ? best.agent : null;
}
